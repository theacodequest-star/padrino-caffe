export type StringKey = keyof typeof strings

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: StringKey, vars?: Record<string, string | number>) => string }
const I18nContext = createContext<Ctx>({ lang: 'sr', setLang: () => {}, t: k => strings[k].sr })

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (load('padrino.lang') === 'en' ? 'en' : 'sr'))

  useEffect(() => {
    document.documentElement.lang = lang === 'sr' ? 'sr-Latn' : 'en'
    save('padrino.lang', lang)
  }, [lang])

  const t = (k: StringKey, vars?: Record<string, string | number>) =>
    (strings[k]?.[lang] ?? "").replace(/\{(\w+)\}/g, (_, v) => String(vars?.[v] ?? ''))
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
